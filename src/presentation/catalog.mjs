export function presentationsById(dataset = presentationCatalog) {
  return new Map(dataset.map((entry) => [entry.id, entry]));
}

export function presentationsBySection(section, dataset = presentationCatalog) {
  return dataset
    .filter((entry) => entry.section === section)
    .sort((left, right) => left.order - right.order);
}

export function presentationUrl(entry, base = "") {
  return `${base}/presentation/${entry.slug}.html`;
}
